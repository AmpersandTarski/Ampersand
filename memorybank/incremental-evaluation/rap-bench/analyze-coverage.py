#!/usr/bin/env python3
"""Static ExecEngine-coverage analysis of the RAP conjuncts (issue #1687
follow-up): which conjuncts does the ExecEngine never force-evaluate, so
that the close-time delta protocol is their only evaluator?

For those conjuncts the delta protocol can genuinely win; for EE-covered
conjuncts the close reuses the ExecEngine's forced full evaluation and the
protocol can only add bookkeeping.

Usage: analyze-coverage.py GENERICS_DIR [--time PORT]

With --time, each non-EE conjunct's full violationsSQL is timed against the
running instance's database (mariadb via docker exec), worst first.
"""
import json
import os
import subprocess
import sys
import time
from pathlib import Path


def bench_root_pw() -> str:
    """The root password of the benchmark databases: generated by setup.sh
    under BENCH_ROOT, never stored in the repository."""
    if pw := os.environ.get("RAP_BENCH_ROOT_PW"):
        return pw
    env = Path(os.environ.get("BENCH_ROOT", "/tmp/rap1687-bench")) / "db.env"
    for line in env.read_text().splitlines():
        if line.startswith("RAP_BENCH_ROOT_PW="):
            return line.split("=", 1)[1]
    sys.exit(f"no RAP_BENCH_ROOT_PW in environment or {env}; run setup.sh")


def main():
    gen = Path(sys.argv[1])
    conjs = json.load(open(gen / "conjuncts.json"))
    roles = json.load(open(gen / "roles.json"))

    ee_rules = set()
    for role in roles:
        if role["name"] == "ExecEngine":
            ee_rules = set(role["maintains"])
    print(f"ExecEngine maintains {len(ee_rules)} rules")

    covered, uncovered = [], []
    for c in conjs:
        rules = set(c["invariantRuleNames"]) | set(c["signalRuleNames"])
        (covered if rules & ee_rules else uncovered).append(c)
    print(f"conjuncts: {len(conjs)} total; EE-covered {len(covered)}; "
          f"NOT EE-covered {len(uncovered)} "
          f"({100 * len(uncovered) / len(conjs):.0f}%)")

    with_delta = sum(1 for c in uncovered if c.get("deltaQueries"))
    print(f"of the uncovered: {with_delta} carry delta queries\n")

    if "--time" in sys.argv:
        port = sys.argv[sys.argv.index("--time") + 1]
        cont = "rap1687bench-db-" + ("off" if port == "8191" else "on")
        db = "rap1687off" if port == "8191" else "rap1687on"
        timed = []
        for c in uncovered:
            sql = c["violationsSQL"].replace('"', "`")
            t0 = time.time()
            r = subprocess.run(
                ["docker", "exec", cont, "mariadb", "-uroot",
                 "-p" + bench_root_pw(), db, "-N", "-B", "-e", sql],
                capture_output=True, text=True)
            ms = 1000 * (time.time() - t0)
            nrows = len(r.stdout.splitlines()) if r.returncode == 0 else -1
            timed.append((ms, nrows, c))
        timed.sort(reverse=True, key=lambda t: t[0])
        print("full violationsSQL cost of NOT-EE-covered conjuncts "
              "(worst 15, docker-exec overhead ~10 ms included):")
        print("ms\trows\tconjunct\trules")
        for ms, nrows, c in timed[:15]:
            rules = ", ".join((c["invariantRuleNames"] +
                               c["signalRuleNames"])[:2])
            print(f"{ms:.0f}\t{nrows}\t{c['id']}\t{rules}")
    else:
        for c in uncovered[:30]:
            rules = ", ".join((c["invariantRuleNames"] +
                               c["signalRuleNames"])[:2])
            print(f"  {c['id']}: {rules}")


if __name__ == "__main__":
    main()
